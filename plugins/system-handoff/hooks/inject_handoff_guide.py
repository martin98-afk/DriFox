# -*- coding: utf-8 -*-
"""BuildSystemPrompt Hook — 会话交接文档使用指引

只对主智能体（current_role="primary"）输出。子智能体不写交接：
它们看到的是任务描述而非完整会话，写出来的交接没有接手价值。

指引只讲「何时写、写什么」，不重复工具 schema 里的格式约束。
"""

_HANDOFF_GUIDE = """## 会话交接（update_handoff）
上下文较长或任务告一段落时，用 `update_handoff` 把当前工作状态写成交接文档；
带 `switch: true` 调用时系统会开新会话，新会话读这份文档接着干。
调用时机（不必每轮都写，写一次覆盖一次）：
- 一个功能改完、一组修改落地并通过验证
- 方案/架构定案，或推翻旧方案改走新路线
- 遇到需要用户确认的阻塞，或准备切到不相关的任务
- 上下文即将接近上限（系统会提示）

内容六节，全文不超过 1500 字：
1. `## 任务目标`：一两句最高层目标
2. `## 已完成`：每条 `path/to/file.py: function()` + 改了什么 + 验证状态
3. `## 关键上下文`：必须记住的路径、约定、数据契约、环境事实
4. `## 未决问题`：症状 + 已尝试 + 阻塞原因
5. `## 剩余任务与下一步`：下一任可直接执行的步骤，按顺序编号
6. `## 用户偏好与约束`：用户明确表达过的要求

`switch` 参数决定写完要不要立刻开新会话继续：
- 一段工作收尾、要换阶段、或被要求「交接」时传 `switch: true`，本轮结束后系统自动开新会话并接着干
- 只是暂存进度、本轮还要继续干活时不要传，交接默默落盘

只写文档本身，不要复述对话过程，不要写「以下是我的总结」这类元描述。"""


def hook(event: str, context: dict) -> str:
    """输出交接文档使用指引（仅主智能体）"""
    if (context or {}).get("current_role") != "primary":
        return ""
    return _HANDOFF_GUIDE
