"""view.py — 全局记忆的 Markdown 视图与注入装包。

自包含：不 import store / manager，输入统一为 replay() 产出的 state。
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any, Dict, List

HEADER = "<!-- generated by assistant_hub memory v2; edit entries via memory_write -->"
LEGACY_TITLE = "历史遗留（未归类）"

_NORM = re.compile(r"\s+")

# 条目正文开头的 id 标签（可能是多个，历史合并残留）：读取视图带 id，模型整篇
# 重写时会把它们原样抄回正文，必须在写入口剥掉，否则每轮重写都在正文里堆 id。
_LEAD_IDS = re.compile(r"^(\[\s*m[0-9a-z]{6}\s*\]\s*)+")

def strip_entry_ids(text: str) -> str:
    """剥掉正文开头的 [id] 标签（可连续多个），其余原样保留。"""
    return _LEAD_IDS.sub("", str(text or "")).strip()

# 注入成本口径：条目正文 + "- " + "[id] "（id 固定 7 位）。配额、预检、
# 健康统计一律用这一套，别再混用文件字符数：文件里的 id、分区标题、空行
# 都不是模型真正要读的内容，按文件算会让预算与注入量对不上。
ENTRY_OVERHEAD = 11
SECTION_OVERHEAD = 4  # "## " + 换行


def _active_by_section(state: Dict[str, Any]) -> Dict[str, List[Dict[str, Any]]]:
    out: Dict[str, List[Dict[str, Any]]] = {}
    for item in state.get("entries", {}).values():
        if item.get("state") != "active" or not item.get("active"):
            continue
        entry = dict(item["active"])
        entry["id"] = item["id"]
        entry["section"] = str(entry.get("section") or "未分区")
        out.setdefault(str(entry.get("section") or ""), []).append(entry)
    for items in out.values():
        items.sort(key=lambda e: (not bool(e.get("pinned")), str(e.get("created_at") or "")))
    return out


def render_markdown(state: Dict[str, Any], sections: List[Dict[str, str]]) -> str:
    by_section = _active_by_section(state)
    lines: List[str] = [HEADER, ""]
    order = [str(s.get("name") or "") for s in (sections or [])]
    for name in order:
        items = by_section.get(name) or []
        if not items:
            continue
        lines.append(f"## {name}")
        for e in items:
            lines.append(f"- [{e['id']}] {e['text']}")
        lines.append("")
    for name, items in by_section.items():
        if name in order or not items:
            continue
        lines.append(f"## {name}")
        for e in items:
            lines.append(f"- [{e['id']}] {e['text']}")
        lines.append("")
    legacy = state.get("legacy") or []
    if legacy:
        lines.append(f"## {LEGACY_TITLE}")
        for item in legacy:
            text = str(item.get("text") or "").strip()
            if text:
                lines.append(f"- {text}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def entry_cost(entry: Dict[str, Any]) -> int:
    """单条注入成本：正文长度 + 行头与 id 开销。"""
    return len(str(entry.get("text") or "")) + ENTRY_OVERHEAD

def state_cost(state: Dict[str, Any]) -> int:
    """全部 active 条目的注入总成本（与 pack_injection 的 used 同口径）。"""
    return sum(entry_cost(e) for items in _active_by_section(state).values() for e in items)

def section_costs(state: Dict[str, Any]) -> Dict[str, int]:
    """按分区的注入成本（未分区的区名照实返回）。"""
    return {name: sum(entry_cost(e) for e in items) for name, items in _active_by_section(state).items()}

def parsed_cost(items: List[Dict[str, Any]]) -> int:
    """待写入条目的注入成本（replace 预检用）。"""
    return sum(len(str(i.get("text") or "")) + ENTRY_OVERHEAD for i in (items or []))


def _injection_priority(entry: dict) -> tuple:
    stamp = entry.get("updated_at") or entry.get("created_at")
    try:
        updated = datetime.fromisoformat(str(stamp))
        if updated.tzinfo is None:
            updated = updated.replace(tzinfo=timezone.utc)
    except ValueError:
        updated = datetime.min.replace(tzinfo=timezone.utc)
    return bool(entry.get("pinned")), updated


def pack_injection(
    state: Dict[str, Any],
    sections: List[Dict[str, str]],
    quotas: Dict[str, int],
    budget: int,
) -> Dict[str, Any]:
    """按分区配额装整条，带分区标题；装不下就整条不进，绝不裁剪半条。

    分区标题必须进注入：system prompt 要求按理性/感性归属写回，注入里看不到
    归属时模型只能靠猜，写回时常把条目塞进错误分区。
    """
    by_section = _active_by_section(state)
    order = [str(s.get("name") or "") for s in (sections or [])]
    order += [name for name in by_section if name not in order]
    tone_by_name = {
        str(s.get("name") or ""): ("emotional" if str(s.get("tone") or "") == "emotional" else "rational")
        for s in (sections or [])
    }
    quota_by_name = {str(s.get("name") or ""): int(quotas.get(str(s.get("name") or ""), budget)) for s in (sections or [])}
    grouped: List[List[Any]] = []
    omitted: List[Dict[str, Any]] = []
    used = 0
    for name in order:
        items = sorted(
            reversed(by_section.get(name, [])),
            key=_injection_priority,
            reverse=True,
        )
        quota = quota_by_name.get(name, budget)
        picked: List[Dict[str, Any]] = []
        local = 0
        for e in items:
            cost = entry_cost(e)
            extra = (len(name) + SECTION_OVERHEAD) if not picked else 0
            if used + cost + extra <= budget and local + cost + extra <= quota:
                picked.append(e)
                used += cost + extra
                local += cost + extra
            else:
                omitted.append(
                    {"id": e["id"], "preview": str(e.get("text") or "")[:20], "entry": e, "section": name}
                )
        if picked:
            grouped.append([name, picked])
    # 同侧额度借用：配额是上限不是任务，同侧（理性/感性）某区装不满时，
    # 把闲置额度让给被挤出的同侧条目。跨侧不借：tone 比例是用户的明确选择。
    side_total: Dict[str, int] = {}
    for name, q in quota_by_name.items():
        tone = tone_by_name.get(name, "rational")
        side_total[tone] = side_total.get(tone, 0) + q
    side_used: Dict[str, int] = {}
    for name, picked in grouped:
        tone = tone_by_name.get(name, "rational")
        side_used[tone] = side_used.get(tone, 0) + len(name) + SECTION_OVERHEAD
        side_used[tone] += sum(entry_cost(e) for e in picked)
    remaining: List[Dict[str, Any]] = []
    for item in omitted:
        e, name = item["entry"], item["section"]
        tone = tone_by_name.get(name, "rational")
        target = next((g for g in grouped if g[0] == name), None)
        cost = entry_cost(e) + (len(name) + SECTION_OVERHEAD if target is None else 0)
        if used + cost <= budget and side_used.get(tone, 0) + cost <= side_total.get(tone, 0):
            if target is None:
                target = [name, []]
                grouped.append(target)
            target[1].append(e)
            used += cost
            side_used[tone] = side_used.get(tone, 0) + cost
        else:
            remaining.append(item)
    omitted = remaining
    lines: List[str] = []
    for name, picked in grouped:
        lines.append(f"## {name}")
        for e in picked:
            lines.append(f"- [{e['id']}] {e['text']}")
    text = "\n".join(lines)
    if omitted:
        refs = "；".join(f"{o['id']} ｜ {o['preview']}" for o in omitted[:10])
        text += f"\n\n未注入条目（预算不足，可按 id 展开）：{refs}"
        if len(omitted) > 10:
            text += f"；另有 {len(omitted) - 10} 条"
    return {"text": text, "omitted": omitted, "used": used, "budget": budget}


def pack_project(text: str, budget: int) -> Dict[str, Any]:
    """超限时按 Markdown 标题取舍整节，无标题的笔记按自然段取舍。"""
    if len(text) <= budget:
        return {"text": text, "omitted": []}
    # 围栏里的标题、空行都是代码内容，不能用作切分位置。
    lines = text.splitlines()
    headings, paragraphs = [], []
    fence = ""
    for index, line in enumerate(lines):
        stripped = line.strip()
        if fence:
            if stripped.startswith(fence) and not stripped.strip(fence[0]):
                fence = ""
            continue
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})", line)
        if marker:
            fence = marker[1]
        elif re.match(r"^ {0,3}#{1,6}\s+", line):
            headings.append(index)
        elif not stripped:
            paragraphs.append(index)
    cuts = [0, *(headings or paragraphs), len(lines)]
    blocks = []
    for start, end in zip(cuts, cuts[1:]):
        block = "\n".join(lines[start:end]).strip()
        if block:
            blocks.append(block)
    notice = "以下块因预算不足未注入"
    kept = []
    omitted = []
    remaining = budget - len(notice) - 2
    for block in blocks:
        size = len(block) + (2 if kept else 0)
        if size <= remaining:
            kept.append(block)
            remaining -= size
        else:
            omitted.append(block.splitlines()[0][:40])
    if kept:
        labels = "、".join(omitted)
        suffix = ("：" + labels)[:remaining]
        return {"text": "\n\n".join([*kept, notice + suffix]), "omitted": omitted}

    # 至少能容纳一小段原文时才给首块预览，避免只注入标记或半个标题。
    marker = "\n…（项目记忆已截断）"
    room = budget - len(marker)
    preview = blocks[0][:room] + marker if blocks and room >= 32 else ""
    return {"text": preview, "omitted": omitted}


def _norm(text: str) -> str:
    return _NORM.sub("", str(text or "")).strip("-—。.,，；;")


def norm_text(text: str) -> str:
    """文本归一化：用于条目去重与整篇 diff 匹配。"""
    return _norm(text)


def diff_replace(
    state: Dict[str, Any], new_text: str, sections: List[Dict[str, str]]
) -> Dict[str, List[Dict[str, Any]]]:
    """把整篇文本与现有条目做文本匹配：保留/新增/软删。不做隐式删除。"""
    parsed = _parse_plain(new_text, sections)
    existing = _active_by_section(state)
    flat: List[Dict[str, Any]] = [e for items in existing.values() for e in items]
    by_norm: Dict[str, Dict[str, Any]] = {_norm(e["text"]): e for e in flat}
    kept: List[Dict[str, Any]] = []
    added: List[Dict[str, Any]] = []
    seen: set = set()
    for item in parsed:
        key = _norm(item["text"])
        hit = by_norm.get(key)
        if hit is not None and key not in seen:
            kept.append(hit)
            seen.add(key)
        else:
            added.append(item)
    removed = [e for k, e in by_norm.items() if k not in seen]
    return {"kept": kept, "added": added, "removed": removed}


def _parse_plain(text: str, sections: List[Dict[str, str]]) -> List[Dict[str, Any]]:
    names = [str(s.get("name") or "") for s in sections or []]
    out: List[Dict[str, Any]] = []
    current = names[0] if names else ""
    for raw in str(text or "").splitlines():
        line = raw.strip()
        if line.startswith("## "):
            title = line[3:].strip()
            current = title if title in names else (names[0] if names else "")
            continue
        if line.startswith("-") and current:
            body = strip_entry_ids(line.lstrip("-").strip())
            if body:
                out.append({"section": current, "text": body})
    return out