"""view.py — 全局记忆的 Markdown 视图与注入装包。

自包含：不 import store / manager，输入统一为 replay() 产出的 state。
"""

from __future__ import annotations

import re
from typing import Any, Dict, List

HEADER = "<!-- generated by assistant_hub memory v2; edit entries via memory_write -->"
LEGACY_TITLE = "历史遗留（未归类）"

_NORM = re.compile(r"\s+")


def _active_by_section(state: Dict[str, Any]) -> Dict[str, List[Dict[str, Any]]]:
    out: Dict[str, List[Dict[str, Any]]] = {}
    for item in state.get("entries", {}).values():
        if item.get("state") != "active" or not item.get("active"):
            continue
        entry = dict(item["active"])
        entry["id"] = item["id"]
        out.setdefault(str(entry.get("section") or ""), []).append(entry)
    for items in out.values():
        items.sort(key=lambda e: (not bool(e.get("pinned")), str(e.get("created_at") or "")))
    return out


def render_markdown(state: Dict[str, Any], sections: List[Dict[str, str]]) -> str:
    by_section = _active_by_section(state)
    lines: List[str] = [HEADER, ""]
    order = [str(s.get("name") or "") for s in (sections or [])]
    for name in order:
        items = by_section.get(name) or []
        if not items:
            continue
        lines.append(f"## {name}")
        for e in items:
            lines.append(f"- [{e['id']}] {e['text']}")
        lines.append("")
    for name, items in by_section.items():
        if name in order or not items:
            continue
        lines.append(f"## {name}")
        for e in items:
            lines.append(f"- [{e['id']}] {e['text']}")
        lines.append("")
    legacy = state.get("legacy") or []
    if legacy:
        lines.append(f"## {LEGACY_TITLE}")
        for item in legacy:
            text = str(item.get("text") or "").strip()
            if text:
                lines.append(f"- {text}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _cost(entry: Dict[str, Any]) -> int:
    return len(str(entry.get("text") or "")) + len(str(entry.get("id") or "")) + 8


def pack_injection(
    state: Dict[str, Any],
    sections: List[Dict[str, str]],
    quotas: Dict[str, int],
    budget: int,
) -> Dict[str, Any]:
    """按分区配额装整条；装不下就整条不进，绝不裁剪半条。"""
    by_section = _active_by_section(state)
    order = [str(s.get("name") or "") for s in (sections or [])]
    selected: List[Dict[str, Any]] = []
    omitted: List[Dict[str, Any]] = []
    used = 0
    for name in order:
        items = by_section.get(name) or []
        quota = int(quotas.get(name, budget))
        local = 0
        for e in items:
            cost = _cost(e)
            if used + cost <= budget and local + cost <= quota:
                selected.append(e)
                used += cost
                local += cost
            else:
                omitted.append({"id": e["id"], "preview": str(e.get("text") or "")[:20]})
    for name, items in by_section.items():
        if name in order:
            continue
        for e in items:
            cost = _cost(e)
            if used + cost <= budget:
                selected.append(e)
                used += cost
            else:
                omitted.append({"id": e["id"], "preview": str(e.get("text") or "")[:20]})
    lines: List[str] = []
    for e in selected:
        lines.append(f"- [{e['id']}] {e['text']}")
    text = "\n".join(lines)
    if omitted:
        refs = "；".join(f"{o['id']} ｜ {o['preview']}" for o in omitted[:10])
        text += f"\n\n未注入条目（预算不足，可按 id 展开）：{refs}"
        if len(omitted) > 10:
            text += f"；另有 {len(omitted) - 10} 条"
    return {"text": text, "omitted": omitted, "used": used, "budget": budget}


def _norm(text: str) -> str:
    return _NORM.sub("", str(text or "")).strip("-—。.,，；;")


def diff_replace(
    state: Dict[str, Any], new_text: str, sections: List[Dict[str, str]]
) -> Dict[str, List[Dict[str, Any]]]:
    """把整篇文本与现有条目做文本匹配：保留/新增/软删。不做隐式删除。"""
    parsed = _parse_plain(new_text, sections)
    existing = _active_by_section(state)
    flat: List[Dict[str, Any]] = [e for items in existing.values() for e in items]
    by_norm: Dict[str, Dict[str, Any]] = {_norm(e["text"]): e for e in flat}
    kept: List[Dict[str, Any]] = []
    added: List[Dict[str, Any]] = []
    seen: set = set()
    for item in parsed:
        key = _norm(item["text"])
        hit = by_norm.get(key)
        if hit is not None and key not in seen:
            kept.append(hit)
            seen.add(key)
        else:
            added.append(item)
    removed = [e for k, e in by_norm.items() if k not in seen]
    return {"kept": kept, "added": added, "removed": removed}


def _parse_plain(text: str, sections: List[Dict[str, str]]) -> List[Dict[str, Any]]:
    names = [str(s.get("name") or "") for s in sections or []]
    out: List[Dict[str, Any]] = []
    current = names[0] if names else ""
    for raw in str(text or "").splitlines():
        line = raw.strip()
        if line.startswith("## "):
            title = line[3:].strip()
            current = title if title in names else (names[0] if names else "")
            continue
        if line.startswith("-") and current:
            body = line.lstrip("-").strip()
            if body:
                out.append({"section": current, "text": body})
    return out