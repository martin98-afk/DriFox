# -*- coding: utf-8 -*-
"""test_memory_v2_compat.py — v2 切换后旧门面的兼容行为（清除/恢复/改名/手改导入）。"""

import importlib.util
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[3]
_MODULE = _ROOT / "plugins" / "assistant_hub" / "assistant_manager.py"
spec = importlib.util.spec_from_file_location("test_memory_v2_compat_mod", str(_MODULE))
m = importlib.util.module_from_spec(spec)
sys.modules.setdefault("test_memory_v2_compat_mod", m)
spec.loader.exec_module(m)


def _fresh_manager(tmp_path):
    m.AssistantManager.reset_instance()
    return m.AssistantManager.get_instance(root_dir=str(tmp_path / "hub"))


def _seed(mgr, aid, section, text):
    r = mgr.append_memory_entry(aid, section, text, origin="user")
    assert r["ok"]
    return r["id"]


def test_read_global_memory_writes_view_file(tmp_path):
    mgr = _fresh_manager(tmp_path)
    a = mgr.create("视图狐")
    _seed(mgr, a.id, "工具与环境", "Windows 换行坑")
    text = mgr.read_global_memory(a.id)
    assert "Windows 换行坑" in text
    on_disk = (mgr.assistant_dir(a.id) / "MEMORY.md").read_text(encoding="utf-8")
    assert on_disk.startswith("<!-- generated by assistant_hub memory v2")
    assert "Windows 换行坑" in on_disk


def test_external_edit_is_imported_not_overwritten(tmp_path):
    mgr = _fresh_manager(tmp_path)
    a = mgr.create("手改狐")
    _seed(mgr, a.id, "工具与环境", "原有条目")
    mgr.read_global_memory(a.id)  # 落盘视图，建立 hash 基线
    p = mgr.assistant_dir(a.id) / "MEMORY.md"
    p.write_text("## 工具与环境\n- 原有条目\n- 手写新增\n", encoding="utf-8")
    text = mgr.read_global_memory(a.id)
    assert "原有条目" in text and "手写新增" in text
    state = mgr.memory_state(a.id)
    assert any("手写新增" in (e.get("text") or "") for e in mgr._core_entries().active_entries(state))


def test_clear_all_memory_clears_v2_events(tmp_path):
    mgr = _fresh_manager(tmp_path)
    a = mgr.create("清除狐")
    _seed(mgr, a.id, "工具与环境", "要被清掉")
    assert mgr.read_global_memory(a.id).count("要被清掉") == 1
    mgr.clear_all_memory(a.id)
    assert "要被清掉" not in mgr.read_global_memory(a.id)


def test_restore_global_snapshot_reimports_events(tmp_path):
    mgr = _fresh_manager(tmp_path)
    a = mgr.create("恢复狐")
    _seed(mgr, a.id, "工具与环境", "快照里的内容")
    mgr.read_global_memory(a.id)
    mgr.snapshot_memory(a.id, "global")
    snaps = mgr.memory_snapshots(a.id, "global")
    assert snaps
    mgr.clear_all_memory(a.id)
    assert "快照里的内容" not in mgr.read_global_memory(a.id)
    r = mgr.restore_memory_snapshot(a.id, "global", snaps[0]["file"])
    assert r.get("ok")
    assert "快照里的内容" in mgr.read_global_memory(a.id)


def test_rename_section_moves_entries(tmp_path):
    mgr = _fresh_manager(tmp_path)
    a = mgr.create("改名狐")
    sections = mgr.memory_sections(a.id)
    old_name = sections[0]["name"]
    _seed(mgr, a.id, old_name, "跟着分区搬家")
    new_sections = [dict(sections[0], name="改名后的区")] + sections[1:]
    r = mgr.set_memory_sections(a.id, new_sections)
    assert r.get("ok") and r.get("renamed")
    state = mgr.memory_state(a.id)
    texts = {(e.get("section"), e.get("text")) for e in mgr._core_entries().active_entries(state)}
    assert ("改名后的区", "跟着分区搬家") in texts

def test_tool_routes_project_and_global_modes(tmp_path, monkeypatch):
    from plugins.assistant_hub.tools import memory_tools

    mgr = _fresh_manager(tmp_path)
    monkeypatch.setattr(memory_tools, "_get_manager", lambda: mgr)
    aid = mgr.active_id()
    ctx = {"workdir": str(tmp_path / "project")}
    write = memory_tools._write_impl
    assert write(ctx, scope="project", content="第一条\n第二条").success
    for mode in ("update", "merge", "plan", "delete"):
        result = write(ctx, scope="project", mode=mode, id="m000001", content="新内容")
        assert not result.success
    assert mgr.read_project_memory(aid, ctx["workdir"]).strip() == "第一条\n第二条"

    entry_id = _seed(mgr, aid, "工具与环境", "正文")
    read = memory_tools._read_impl
    assert "正文" in read(ctx, scope="global", id=entry_id).content
    plan = [{"op": "update", "id": entry_id, "content": "修改"}, {"op": "pin", "id": entry_id, "pinned": True}]
    assert write(ctx, scope="global", mode="plan", plan=plan).success
    assert "修改" in read(ctx, scope="global", id=entry_id).content
    assert mgr.memory_state(aid)["entries"][entry_id]["active"]["pinned"]
    assert write(ctx, scope="global", mode="delete", id=entry_id).success
    assert not read(ctx, scope="global", id=entry_id).success


def test_failed_plan_keeps_original_journal(tmp_path, monkeypatch):
    import pytest

    mgr = _fresh_manager(tmp_path)
    aid = mgr.active_id()
    entry_id = _seed(mgr, aid, "工具与环境", "原文")
    mod = mgr._core_entries()
    path = mod.journal_path(mgr.assistant_dir(aid), mgr.memory_device_id())
    original = path.read_bytes()
    delete = {"op": "delete", "id": entry_id}
    update = {"op": "update", "id": entry_id, "content": "修改"}
    assert not mgr.apply_memory_plan(aid, [delete, update])["ok"]
    assert path.read_bytes() == original

    def fail_publish(src, dst):
        raise OSError("模拟提交失败")

    with monkeypatch.context() as patch:
        patch.setattr(mod.os, "replace", fail_publish)
        with pytest.raises(OSError, match="提交失败"):
            mgr.apply_memory_plan(aid, [update, delete])
    assert path.read_bytes() == original
    assert mgr.apply_memory_plan(aid, [update, delete])["ok"]
    item = mgr.memory_state(aid)["entries"][entry_id]
    assert item["state"] == "deleted"
    assert [e["text"] for e in item["versions"]] == ["原文", "修改"]
