# -*- coding: utf-8 -*-
"""test_memory_view.py — 全局记忆视图渲染与注入装包。"""

import importlib.util
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[3]
_BASE = _ROOT / "plugins" / "assistant_hub" / "core" / "memory"

_entries_spec = importlib.util.spec_from_file_location("test_memory_view_entries", str(_BASE / "entries.py"))
entries = importlib.util.module_from_spec(_entries_spec)
sys.modules.setdefault("test_memory_view_entries", entries)
_entries_spec.loader.exec_module(entries)

_view_spec = importlib.util.spec_from_file_location("test_memory_view_mod", str(_BASE / "view.py"))
view = importlib.util.module_from_spec(_view_spec)
sys.modules.setdefault("test_memory_view_mod", view)
_view_spec.loader.exec_module(view)

SECTIONS = [
    {"name": "工具与环境", "hint": "工具坑", "tone": "rational", "detail": "工具自身行为"},
    {"name": "用户偏好", "hint": "他是什么人", "tone": "emotional", "detail": "稳定理解"},
]


def _state(*pairs):
    state = entries.empty_state()
    for section, text in pairs:
        e = entries.new_entry(section, text, origin="user")
        entries._apply_put(state, {"op": "put", "id": e["id"], "entry": e})
    return state


# ── T6 渲染 ──────────────────────────────────────────────


def test_render_has_generated_header_and_ids():
    md = view.render_markdown(_state(("工具与环境", "Windows 换行")), SECTIONS)
    assert md.splitlines()[0].startswith("<!-- generated by assistant_hub memory v2")
    assert "## 工具与环境" in md
    assert "- [m" in md
    assert "Windows 换行" in md


def test_render_skips_empty_sections_and_lists_legacy():
    state = _state(("工具与环境", "一条"))
    state["legacy"] = [{"text": "旧散文", "reason": "unparsed", "line_no": 3}]
    md = view.render_markdown(state, SECTIONS)
    assert "## 用户偏好" not in md
    assert "历史遗留" in md
    assert "旧散文" in md


def test_render_hides_deleted_and_superseded():
    state = _state(("工具与环境", "活着"))
    dead = entries.new_entry("工具与环境", "死了")
    entries._apply_put(state, {"op": "put", "id": dead["id"], "entry": dead})
    entries._apply_del(state, {"op": "del", "id": dead["id"]})
    md = view.render_markdown(state, SECTIONS)
    assert "活着" in md
    assert "死了" not in md


# ── T7 装包 ──────────────────────────────────────────────


def test_pack_prefers_pinned_and_never_cuts_entry():
    state = entries.empty_state()
    big = entries.new_entry("工具与环境", "长" * 200, origin="user")
    entries._apply_put(state, {"op": "put", "id": big["id"], "entry": big})
    entries._apply_pin(state, {"op": "pin", "id": big["id"], "pinned": True})
    small = entries.new_entry("用户偏好", "短条目", origin="user")
    entries._apply_put(state, {"op": "put", "id": small["id"], "entry": small})
    quotas = {"工具与环境": 2500, "用户偏好": 1500}
    packed = view.pack_injection(state, SECTIONS, quotas, budget=230)
    assert "长" * 200 in packed["text"]
    assert packed["omitted"][0]["id"] == small["id"]
    assert packed["used"] <= 230


def test_pack_reports_all_omitted_without_truncating():
    state = entries.empty_state()
    for i in range(3):
        e = entries.new_entry("工具与环境", f"条目{i}" + "x" * 60, origin="user")
        entries._apply_put(state, {"op": "put", "id": e["id"], "entry": e})
    packed = view.pack_injection(state, SECTIONS, {"工具与环境": 10}, budget=10)
    assert len(packed["omitted"]) == 3
    assert all("…" not in o["preview"] for o in packed["omitted"])


# ── T12 整条让位 ─────────────────────────────────────────


def test_snapshot_block_uses_packing_not_truncation():
    state = _state(("工具与环境", "甲" * 50))
    packed = view.pack_injection(state, SECTIONS, {"工具与环境": 40}, budget=40)
    assert "甲" * 50 not in packed["text"]
    assert packed["omitted"][0]["id"]
    assert "未注入条目" in packed["text"]